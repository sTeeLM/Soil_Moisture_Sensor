void oled_ext_draw_power(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t percent, bool last_on_off)
{
  uint8_t cell_w, cell_h, cell_w_last;
  
  if(w < 4 || h < 4) return;
  
  // 计算每一个格子的宽度，高度
  cell_h = h - 4;
  cell_w = (w - 4)/ 4;
  
  if(cell_h < 1 || cell_w < 1) return;  
  cell_w --;
  
  cell_w_last = (w - 4) % 4 + cell_w + 1;
  
  // 画外框
  oled_fill_rect(x, y, w, h, true);
  oled_fill_rect(x+1, y+1, w-2, h-2, false);
  
  if(percent < 25 ) {
    if(last_on_off)
      oled_fill_rect(x + 2, y + 2, cell_w, cell_h, true);
  } else if(percent >= 25 && percent < 50) {
    oled_fill_rect(x + 2, y + 2, cell_w, cell_h, true);
    if(last_on_off)
      oled_fill_rect(x + 2 + (cell_w + 1), y + 2, cell_w, cell_h, true);
  } else if(percent >= 50 && percent < 75) {
    oled_fill_rect(x + 2, y + 2, cell_w, cell_h, true);
    oled_fill_rect(x + 2 + (cell_w + 1), y + 2, cell_w, cell_h, true);
    if(last_on_off)
      oled_fill_rect(x + 2 + (cell_w + 1) * 2, y + 2, cell_w, cell_h, true);
  } else {
    oled_fill_rect(x + 2, y + 2, cell_w, cell_h, true);
    oled_fill_rect(x + 2 + (cell_w + 1), y + 2, cell_w, cell_h, true);
    oled_fill_rect(x + 2 + (cell_w + 1) * 2, y + 2, cell_w, cell_h, true);
    if(last_on_off)
      oled_fill_rect(x + 2 + (cell_w + 1) * 3, y + 2, cell_w_last, cell_h, true);
  }
  
}

// 在 x, y位置写字符串str, str是宽字符和ascii的混合(中英文混合）
// 英文字符必须占两个字节，
// 高位全零, 低位为ascii码
// 两者可以使用不一样大小的font, 所有字符会顶对齐
// ascii_font: ascii字符使用的font
// wide_char_font: 宽字符使用的font
// 如果字库中没有对应字符，打印一个方块
void oled_ext_draw_wstring(
  uint8_t x, 
  uint8_t y, 
  const wchar_t * str, 
  mini_font_type_t ascii_font,
  mini_font_type_t wide_char_font,
  oled_draw_type_t type)
{
  const wchar_t * p = str;
  const uint8_t * font = NULL;
  uint8_t w, h, offset = 0;

  while(p && *p != 0) {
    if((font = mini_font_lookup(*p, (*p & 0xFF00) ? wide_char_font : ascii_font, &w, &h)) != NULL) {
      oled_draw_bitmap(x + offset, y, w, h, font, type);
    } else {
      oled_fill_rect(x + offset, y, w, h, true);
    }
    p ++;
    offset += w;
  }
}

// 在 x, y位置写字符串str, str必须是ascii字符
// ascii_font: ascii字符使用的font
// 如果字库中没有对应字符，打印一个方块
void oled_ext_draw_string(
  uint8_t x, 
  uint8_t y, 
  const char * str, 
  mini_font_type_t ascii_font,
  oled_draw_type_t type)
{
  const char * p = str;
  wchar_t c;
  const uint8_t * font = NULL;
  uint8_t w, h, offset = 0;
  while(p && *p != 0) {
    c = *p;
    if((font = mini_font_lookup(c, ascii_font, &w, &h)) != NULL) {
      oled_draw_bitmap(x + offset, y, w, h, font, type);
    } else {
      oled_fill_rect(x + offset, y, w, h, true);
    }
    p ++;
    offset += w;
  }
}
